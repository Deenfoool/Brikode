import { projectToJson, validateProject } from "./ir.js";
import { requiredEnvForProject } from "./connectors.js";
import { downloadBlob, slugify } from "./utils.js";

let runtimeSourcePromise = null;

async function getRuntimeSource() {
  if (!runtimeSourcePromise) {
    runtimeSourcePromise = fetch("./assets/runtime-template.mjs", { cache: "no-store" })
      .then(response => {
        if (!response.ok) throw new Error("Could not load the runtime template.");
        return response.text();
      });
  }
  return runtimeSourcePromise;
}

function usesConnector(project, id) {
  if (project.trigger?.type?.startsWith(id + ".")) return true;

  const walk = steps => (steps || []).some(step =>
    step.action?.startsWith(id + ".") ||
    (step.type === "condition" && (walk(step.then) || walk(step.else)))
  );

  return walk(project.steps);
}

function packageJson(project) {
  const dependencies = {};
  if (usesConnector(project, "discord")) {
    dependencies["discord.js"] = "14.27.0";
  }

  return JSON.stringify({
    name: slugify(project.name),
    version: "1.0.0",
    private: true,
    type: "module",
    engines: { node: ">=20.10" },
    scripts: {
      start: "node --env-file=.env src/runtime.mjs",
      "start:plain": "node src/runtime.mjs"
    },
    dependencies
  }, null, 2) + "\n";
}

function envExample(project) {
  const lines = [
    "# Copy this file to .env and fill only the values your workflow needs.",
    "# Never commit .env.",
    ""
  ];

  for (const item of requiredEnvForProject(project)) {
    lines.push(item.env + "=");
  }

  if (project.trigger?.type === "webhook.incoming") {
    lines.push("PORT=3000");
  }

  return [...new Set(lines)].join("\n") + "\n";
}

function connectorSetup(project) {
  const sections = [];
  if (usesConnector(project, "telegram")) {
    sections.push([
      "### Telegram",
      "",
      "1. Create or choose a bot with BotFather.",
      "2. Put the bot token in `TELEGRAM_BOT_TOKEN`.",
      "3. The runtime uses Telegram long polling, so no public webhook URL is required."
    ].join("\n"));
  }
  if (usesConnector(project, "discord")) {
    sections.push([
      "### Discord",
      "",
      "1. Create/select an application in the Discord Developer Portal and add a bot.",
      "2. Put its token in `DISCORD_BOT_TOKEN`.",
      "3. Put the application ID in `DISCORD_APPLICATION_ID` when using slash commands.",
      "4. For message triggers, enable the Message Content intent for the bot when required by your Discord application."
    ].join("\n"));
  }
  if (project.trigger?.type === "webhook.incoming") {
    sections.push([
      "### Webhook",
      "",
      "The runtime listens on `PORT` (default `3000`) at path `" + (project.trigger.config?.path || "/hook") + "`.",
      "Expose that port through your own HTTPS reverse proxy or hosting platform when the webhook must be public."
    ].join("\n"));
  }
  return sections.join("\n\n") || "No connector-specific setup is required.";
}

function generatedReadme(project) {
  const env = requiredEnvForProject(project);
  const envLines = env.length
    ? env.map(item => "- \`" + item.env + "\` — " + item.label + " (" + item.connector + ")").join("\n")
    : "- No connector credentials are required by this workflow.";

  return [
    "# " + project.name,
    "",
    "Generated by Brikode.",
    "",
    "## Requirements",
    "",
    "- Node.js 20.10 or newer",
    "",
    "## Setup",
    "",
    "1. Copy \`.env.example\` to \`.env\`.",
    "2. Fill the required values listed below.",
    "3. Run \`npm install\`.",
    "4. Run \`npm start\`.",
    "",
    "## Environment",
    "",
    envLines,
    "",
    "## Connector setup",
    "",
    connectorSetup(project),
    "",
    "## Workflow",
    "",
    "- Trigger: \`" + (project.trigger?.type || "none") + "\`",
    "- Canonical workflow: \`workflow.json\`",
    "- Runtime: \`src/runtime.mjs\`",
    "",
    "Do not put production tokens inside workflow.json. Secrets are read from environment variables at runtime.",
    ""
  ].join("\n");
}

function dockerfile() {
  return [
    "FROM node:22-alpine",
    "WORKDIR /app",
    "COPY package*.json ./",
    "RUN npm install --omit=dev",
    "COPY . .",
    "CMD [\"npm\", \"start\"]",
    ""
  ].join("\n");
}

function composeFile(project) {
  const portLine = project.trigger?.type === "webhook.incoming"
    ? "    ports:\n      - \"3000:3000\"\n"
    : "";

  return [
    "services:",
    "  bot:",
    "    build: .",
    "    restart: unless-stopped",
    "    env_file:",
    "      - .env",
    portLine.trimEnd(),
    ""
  ].filter(Boolean).join("\n") + "\n";
}

export function exportReadiness(project) {
  const diagnostics = validateProject(project);
  const checks = [
    {
      id: "valid",
      ok: !diagnostics.some(item => item.severity === "error"),
      label: "Workflow has no blocking validation errors"
    },
    {
      id: "trigger",
      ok: Boolean(project.trigger),
      label: "A trigger is configured"
    },
    {
      id: "steps",
      ok: Array.isArray(project.steps) && project.steps.length > 0,
      label: "Workflow contains at least one step"
    },
    {
      id: "secrets",
      ok: true,
      label: "Secrets are referenced through environment variables"
    }
  ];

  return { checks, diagnostics };
}

export async function exportSelfHosted(project, options = {}) {
  const readiness = exportReadiness(project);
  if (!readiness.checks.every(check => check.ok)) {
    throw new Error("Fix the export readiness errors before downloading.");
  }

  if (!globalThis.JSZip) {
    throw new Error("JSZip did not load. Check the network connection and reload Brikode.");
  }

  const runtime = await getRuntimeSource();
  const zip = new JSZip();
  zip.file("workflow.json", projectToJson(project));
  zip.file("package.json", packageJson(project));
  zip.file(".env.example", envExample(project));
  zip.file(".gitignore", ".env\nnode_modules/\n");
  zip.file("README.md", generatedReadme(project));
  zip.file("src/runtime.mjs", runtime);

  if (options.docker) {
    zip.file("Dockerfile", dockerfile());
    zip.file("docker-compose.yml", composeFile(project));
    zip.file(".dockerignore", "node_modules\n.env\n.git\n");
  }

  const blob = await zip.generateAsync({
    type: "blob",
    compression: "DEFLATE",
    compressionOptions: { level: 6 }
  });

  const filename = slugify(project.name) + "-self-host.zip";
  downloadBlob(blob, filename);
  return filename;
}
